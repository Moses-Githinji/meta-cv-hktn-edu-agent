#!/usr/bin/env python3
"""Email a run's documents as PDF or Word attachments.

    ./helper send RUN_ID --what scheme --format pdf --to teacher@school.edu
        [--subject "..."] [--message "..."] [--dry-run] [--json]

RUN_ID is the id ./helper run prints at the end. Missed it? It is the
folder name in workspace/runs/, or pick the run in the console's run list.

Builds the export with the same builders as ./helper export, so the
attachment always matches the current record. Configuration comes from
the environment (.env): SMTP_HOST (required), SMTP_PORT (default 587),
SMTP_USER, SMTP_PASSWORD, SMTP_FROM (required), SMTP_TLS (default yes).
Port 465 uses SSL; other ports use STARTTLS unless SMTP_TLS=no (a local
relay only). --dry-run builds everything and prints the summary without
connecting. Every send is appended to the run's audit log (recipients
and document, never the message body or credentials).
"""

from __future__ import annotations

import argparse
import os
import re
import smtplib
import sys
from email.message import EmailMessage
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from edu_kit import audit  # noqa: E402
from export.build import WHAT, ExportError, build  # noqa: E402
from export.docx import build_docx  # noqa: E402
from export.pdf import build_pdf  # noqa: E402

MAX_RECIPIENTS = 10
MAX_ATTACHMENT_BYTES = 10 * 1024 * 1024
ADDRESS = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")
FORMATS = ("pdf", "docx")


class SendError(ValueError):
    """The email cannot be sent. Safe to show (never carries credentials)."""


def smtp_config(env: dict | None = None) -> dict:
    env = os.environ if env is None else env
    host = (env.get("SMTP_HOST") or "").strip()
    sender = (env.get("SMTP_FROM") or "").strip()
    if not host:
        raise SendError("SMTP_HOST is not set: add it to .env (see .env.example)")
    if not sender or not ADDRESS.match(sender):
        raise SendError("SMTP_FROM must be a valid email address in .env")
    try:
        port = int((env.get("SMTP_PORT") or "587").strip())
    except ValueError:
        raise SendError("SMTP_PORT must be a number") from None
    return {
        "host": host,
        "port": port,
        "user": (env.get("SMTP_USER") or "").strip(),
        "password": env.get("SMTP_PASSWORD") or "",
        "sender": sender,
        "tls": (env.get("SMTP_TLS") or "yes").strip().lower() not in ("no", "0", "false"),
    }


def recipients(raw: str) -> list:
    found = [a.strip() for a in raw.split(",") if a.strip()]
    if not found:
        raise SendError("--to needs at least one email address")
    if len(found) > MAX_RECIPIENTS:
        raise SendError(f"at most {MAX_RECIPIENTS} recipients per email")
    for address in found:
        if not ADDRESS.match(address):
            raise SendError(f"not an email address: {address}")
    return found


def attachment(root: Path, run_id: str, what: str, fmt: str) -> tuple[str, str, bytes]:
    """(title, filename, data) for one export kind, built fresh from the record."""
    if what not in WHAT:
        raise SendError(f"what must be one of {', '.join(WHAT)}")
    if fmt not in FORMATS:
        raise SendError(f"format must be one of {', '.join(FORMATS)}")
    try:
        title, flow, footer = build(root, run_id, what)
        landscape = what == "scheme"
        if fmt == "pdf":
            data = build_pdf(title, flow, footer, landscape=landscape)
        else:
            data = build_docx(title, flow, footer, landscape=landscape)
    except ExportError as error:
        raise SendError(str(error)) from None
    if len(data) > MAX_ATTACHMENT_BYTES:
        raise SendError(f"attachment is too large ({len(data)} bytes)")
    return title, f"{run_id}-{what}.{fmt}", data


def send_run(
    root: Path,
    run_id: str,
    what: str,
    fmt: str,
    to: list,
    subject: str = "",
    message: str = "",
    dry_run: bool = False,
    config: dict | None = None,
) -> dict:
    """Build the export and email it. Returns the summary (safe to print)."""
    root = Path(root)
    if not (root / "workspace/case_records" / f"{run_id}.json").is_file():
        raise SendError(f"no case record for {run_id}")
    title, filename, data = attachment(root, run_id, what, fmt)
    subject = subject.strip() or f"{title} [{run_id}]"
    message = message.strip() or (
        f"Attached: {filename}.\n\nGenerated by the teaching agent "
        f"(run {run_id}). Reply to this email to reach the sender."
    )
    summary = {
        "run_id": run_id,
        "what": what,
        "format": fmt,
        "to": to,
        "subject": subject,
        "file": filename,
        "bytes": len(data),
        "dry_run": dry_run,
    }
    if dry_run:
        return summary
    cfg = config if config is not None else smtp_config()
    email = EmailMessage()
    email["From"] = cfg["sender"]
    email["To"] = ", ".join(to)
    email["Subject"] = subject
    email.set_content(message)
    maintype, subtype = ("application", "pdf") if fmt == "pdf" else (
        "application",
        "vnd.openxmlformats-officedocument.wordprocessingml.document",
    )
    email.add_attachment(data, maintype=maintype, subtype=subtype, filename=filename)
    try:
        if cfg["port"] == 465:
            server: smtplib.SMTP = smtplib.SMTP_SSL(cfg["host"], cfg["port"], timeout=30)
        else:
            server = smtplib.SMTP(cfg["host"], cfg["port"], timeout=30)
        with server:
            if cfg["port"] != 465 and cfg["tls"]:
                server.starttls()
            if cfg["user"]:
                server.login(cfg["user"], cfg["password"])
            server.send_message(email)
    except (OSError, smtplib.SMTPException) as error:
        raise SendError(f"could not send via {cfg['host']}:{cfg['port']}: {error}") from None
    audit.append(
        root,
        run_id,
        "document_shared",
        {"what": what, "format": fmt, "to": list(to), "subject": subject, "bytes": len(data)},
    )
    return summary


def main(argv: list | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("run_id")
    parser.add_argument("--what", choices=WHAT, required=True)
    parser.add_argument("--format", choices=FORMATS, required=True)
    parser.add_argument("--to", required=True, help="recipient(s), comma-separated")
    parser.add_argument("--subject", default="")
    parser.add_argument("--message", default="")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--json", action="store_true", help="print the summary as JSON")
    args = parser.parse_args(argv)
    try:
        to = recipients(args.to)
        result = send_run(
            ROOT, args.run_id, args.what, args.format, to,
            args.subject, args.message, args.dry_run,
        )
    except (SendError, ExportError) as error:
        print(f"send failed: {error}", file=sys.stderr)
        return 1
    if args.json:
        import json

        print(json.dumps(result, indent=2))
    elif result["dry_run"]:
        print(f"would send {result['file']} ({result['bytes']} bytes) to {', '.join(to)}")
    else:
        print(f"sent {result['file']} ({result['bytes']} bytes) to {', '.join(to)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
